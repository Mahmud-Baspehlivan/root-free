const STRINGS: Record<Lang, Record<Key, string>> = { en, tr };
const STORE_KEY = "rootfree_lang";

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === "tr" || saved === "en") return saved;
  } catch {
    // storage blocked: fall back to the browser language
  }
  return (navigator.languages?.[0] || navigator.language || "").toLowerCase().startsWith("tr") ? "tr" : "en";
}

let current: Lang = detect();

export function lang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  current = l;
  try {
    localStorage.setItem(STORE_KEY, l);
  } catch {
    // not remembered, still switched for this page
  }
  applyStatic();
}

/** A text in the current language, with {name} placeholders filled in. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return STRINGS[current][key].replace(/\{(\w+)\}/g, (_, v: string) => String(vars[v] ?? `{${v}}`));
}

/** Translate the static texts of the page. */
export function applyStatic(root: ParentNode = document): void {
  document.documentElement.lang = current;
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((e) => (e.textContent = t(e.dataset.i18n as Key)));
  root
    .querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]")
    .forEach((e) => (e.placeholder = t(e.dataset.i18nPlaceholder as Key)));
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((e) => {
    e.title = t(e.dataset.i18nTitle as Key);
    e.setAttribute("aria-label", e.title);
  });
}
